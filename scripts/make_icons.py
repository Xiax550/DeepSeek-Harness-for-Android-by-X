#!/usr/bin/env python3
"""Generate DHA launcher and notification icons from the project artwork.

The canonical source is ``assets/dha-icon-source.png``. It is a project asset
supplied by the DHA maintainer; see ``assets/README.md`` for provenance.

The same artwork is used for light and night launch icons so the brand does not
invert unexpectedly. Adaptive foregrounds are full-bleed because Android applies
the device launcher's mask to the outer layers; legacy icons remain square and
are masked by the launcher as well.

Usage:
  python make_icons.py [ignored-upstream-dir] <app-res-dir>

The first argument is accepted for compatibility with older build commands.
"""
from __future__ import annotations

import sys
from pathlib import Path

from PIL import Image, ImageFilter, ImageOps

LEGACY = {"mdpi": 48, "hdpi": 72, "xhdpi": 96, "xxhdpi": 144, "xxxhdpi": 192}
FOREGROUND = {"mdpi": 108, "hdpi": 162, "xhdpi": 216, "xxhdpi": 324, "xxxhdpi": 432}
BACKGROUND = (9, 14, 29)


def source_path(dst: Path) -> Path:
    return dst.parent.parent / "assets" / "dha-icon-source.png"


def square(image: Image.Image, size: int) -> Image.Image:
    """Center-crop by transparency when possible, then resize without stretching."""
    image = ImageOps.exif_transpose(image).convert("RGBA")
    if image.getchannel("A").getextrema()[0] < 255:
        bbox = image.getchannel("A").getbbox()
        if bbox is not None:
            image = image.crop(bbox)
    side = min(image.size)
    left = (image.width - side) // 2
    top = (image.height - side) // 2
    image = image.crop((left, top, left + side, top + side))
    return image.resize((size, size), Image.Resampling.LANCZOS)


def write_adaptive_icon(anydpi: Path) -> None:
    anydpi.mkdir(parents=True, exist_ok=True)
    (anydpi / "ic_launcher.xml").write_text(
        '<?xml version="1.0" encoding="utf-8"?>\n'
        "<!-- Generated by scripts/make_icons.py from assets/dha-icon-source.png. -->\n"
        '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
        '    <background android:drawable="@color/icon_background" />\n'
        '    <foreground android:drawable="@mipmap/ic_launcher_foreground" />\n'
        "</adaptive-icon>\n",
        encoding="utf-8",
    )


def write_backgrounds(dst: Path) -> None:
    colour = "#{:02X}{:02X}{:02X}".format(*BACKGROUND)
    for suffix in ("", "-night"):
        values = dst / f"values{suffix}"
        values.mkdir(parents=True, exist_ok=True)
        (values / "icon_background.xml").write_text(
            '<?xml version="1.0" encoding="utf-8"?>\n'
            "<resources>\n"
            f'    <color name="icon_background">{colour}</color>\n'
            "</resources>\n",
            encoding="utf-8",
        )


def write_notification_icon(image: Image.Image, dst: Path) -> None:
    """Build a white, transparent notification mask from the artwork highlight."""
    target = dst / "drawable-nodpi"
    target.mkdir(parents=True, exist_ok=True)
    mark = square(image, 192).convert("RGB")
    luminance = mark.convert("L")
    # The source has a dark background. Keep only foreground highlights, then
    # normalize the strongest alpha so the status-bar glyph remains legible.
    alpha = luminance.point(lambda value: 0 if value < 48 else min(255, (value - 48) * 2))
    alpha = alpha.filter(ImageFilter.GaussianBlur(0.45))
    bounds = alpha.getbbox()
    if bounds is not None:
        alpha = alpha.crop(bounds)
    alpha = ImageOps.contain(alpha, (144, 144), Image.Resampling.LANCZOS)
    canvas = Image.new("L", (192, 192), 0)
    canvas.paste(alpha, ((192 - alpha.width) // 2, (192 - alpha.height) // 2))
    white = Image.new("RGBA", canvas.size, (255, 255, 255, 255))
    white.putalpha(canvas)
    white.save(target / "ic_dha_notification.png", optimize=True)


def main() -> None:
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    dst = Path(sys.argv[2]).resolve()
    src = source_path(dst)
    if not src.is_file():
        sys.exit(f"missing project icon source: {src}")

    with Image.open(src) as opened:
        source = opened.copy()

    for density, size in FOREGROUND.items():
        target = dst / f"mipmap-{density}-v4"
        target.mkdir(parents=True, exist_ok=True)
        foreground = square(source, size)
        foreground.save(target / "ic_launcher_foreground.png", optimize=True)
        night = dst / f"mipmap-night-{density}-v4"
        night.mkdir(parents=True, exist_ok=True)
        foreground.save(night / "ic_launcher_foreground.png", optimize=True)

    for density, size in LEGACY.items():
        icon = square(source, size)
        target = dst / f"mipmap-{density}-v4"
        target.mkdir(parents=True, exist_ok=True)
        icon.save(target / "ic_launcher.png", optimize=True)
        night = dst / f"mipmap-night-{density}-v4"
        night.mkdir(parents=True, exist_ok=True)
        icon.save(night / "ic_launcher.png", optimize=True)

    write_adaptive_icon(dst / "mipmap-anydpi-v26")
    write_backgrounds(dst)
    write_notification_icon(source, dst)

    legacy_whale = dst / "drawable" / "ic_whale_monochrome.xml"
    if legacy_whale.exists():
        legacy_whale.unlink()

    print(f"icons written under {dst}")
    print(f"  source: {src}")


if __name__ == "__main__":
    main()
